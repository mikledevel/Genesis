"""PostgreSQL driver for GenesisDB's bounded SQL dialect.

The repository keeps qmark parameters and text UTC timestamps for compatibility
with existing SQLite data. Values always remain bound parameters. This adapter
handles only the SQLite date expressions and DDL used by GenesisDB; business
queries and transaction boundaries stay in the repository.
"""
import atexit
import re
import threading
from contextlib import contextmanager

import psycopg
from psycopg_pool import ConnectionPool

_POOLS = {}
_POOL_LOCK = threading.Lock()
_SCHEMA_LOCK = threading.Lock()
_READY = set()
_QUOTED = re.compile(r"'(?:''|[^'])*'")
_UTC = "(CURRENT_TIMESTAMP AT TIME ZONE 'UTC')"
_FORMAT = "'YYYY-MM-DD HH24:MI:SS'"


def postgres_sql(sql):
    """Translate repository SQL, never parameter values, into PostgreSQL SQL."""
    if sql.strip().upper().startswith('PRAGMA '):
        return None
    sql = re.sub(r"\bINTEGER PRIMARY KEY AUTOINCREMENT\b", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql)
    sql = re.sub(r"\bINTEGER\b", "BIGINT", sql)
    sql = re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql)
    sql = re.sub(r"\bADD COLUMN\b(?! IF NOT EXISTS)", "ADD COLUMN IF NOT EXISTS", sql)

    def clock(match):
        modifier = match.group(1)
        if not modifier:
            value = _UTC
        elif modifier == "'start of month'":
            value = f"date_trunc('month', {_UTC})"
        else:
            value = f"({_UTC} + CAST({modifier} AS interval))"
        return f"to_char({value}, {_FORMAT})"

    sql = re.sub(r"datetime\('now'(?:,\s*(\?|'[^']*'))?\)", clock, sql)
    # Dates are returned as ISO text, matching the SQLite repository contract.
    sql = re.sub(r"date\('now',\s*('[^']*')\)",
                 lambda m: f"to_char({_UTC} + CAST({m.group(1)} AS interval), 'YYYY-MM-DD')", sql)
    sql = re.sub(r"\bdate\(([\w.]+|\?)\)", r"left(\1, 10)", sql)

    # psycopg treats '%' as parameter syntax; escape SQL literals separately.
    parts = []
    end = 0
    for match in _QUOTED.finditer(sql):
        parts.append(sql[end:match.start()].replace('%', '%%').replace('?', '%s'))
        parts.append(match.group().replace('%', '%%'))
        end = match.end()
    parts.append(sql[end:].replace('%', '%%').replace('?', '%s'))
    return ''.join(parts)


def pool_for(url):
    with _POOL_LOCK:
        if url not in _POOLS:
            def configure(conn):
                conn.execute('SET search_path TO genesis, pg_catalog')
                conn.execute("SET TIME ZONE 'UTC'")
                conn.commit()
            _POOLS[url] = ConnectionPool(
                url, min_size=0, max_size=4, timeout=15, open=True,
                kwargs={'connect_timeout': 10, 'prepare_threshold': None},
                configure=configure,
            )
        return _POOLS[url]


@atexit.register
def close_pools():
    for pool in _POOLS.values():
        pool.close()
    _POOLS.clear()


class Connection:
    def __init__(self, url):
        self._lease = pool_for(url).connection()

    def __enter__(self):
        self.raw = self._lease.__enter__()
        return self

    def __exit__(self, *args):
        return self._lease.__exit__(*args)

    def execute(self, sql, params=()):
        statement = postgres_sql(sql)
        if statement is None:
            return self.raw.execute('SELECT 1')
        return self.raw.execute(statement, params)

    def executescript(self, script):
        for statement in script.split(';'):
            if statement.strip():
                self.execute(statement)

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()


@contextmanager
def schema_initialization(url):
    """Initialize once per process; serialize migrations across application workers."""
    with _SCHEMA_LOCK:
        if url in _READY:
            yield False
            return
        with pool_for(url).connection() as conn:
            conn.execute('SELECT pg_advisory_lock(712064952)')
            try:
                yield True
                _READY.add(url)
            finally:
                conn.rollback()
                conn.execute('SELECT pg_advisory_unlock(712064952)')
                conn.commit()
